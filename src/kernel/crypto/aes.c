static const u32 g_rcon[15] = {
    0x00000000, 0x01000000, 0x02000000, 0x04000000, 0x08000000,
    0x10000000, 0x20000000, 0x40000000, 0x80000000, 0x1b000000,
    0x36000000, 0x6c000000, 0xd8000000, 0xab000000, 0x4d000000};

static u8 xtime(u8 value)
{
    return (u8)((value << 1) ^ ((value & 0x80) ? 0x1B : 0));
}

static u8 gmul(u8 a, u8 b)
{
    u8 result = 0;
    while (b) {
        if (b & 1)
            result ^= a;
        a = xtime(a);
        b >>= 1;
    }
    return result;
}

static u32 sub_word(u32 word)
{
    return ((u32)g_sbox[(word >> 24) & 0xFF] << 24) |
           ((u32)g_sbox[(word >> 16) & 0xFF] << 16) |
           ((u32)g_sbox[(word >> 8) & 0xFF] << 8) |
           g_sbox[word & 0xFF];
}

static u32 rot_word(u32 word)
{
    return (word << 8) | (word >> 24);
}

/* Expand a 128/192/256-bit key into the round-key words. */
int aes_set_key(struct aes_ctx *ctx, const u8 *key, usize key_len)
{
    if (!ctx || !key)
        return -1;
    int nk;
    if (key_len == 16)
        nk = 4;
    else if (key_len == 24)
        nk = 6;
    else if (key_len == 32)
        nk = 8;
    else
        return -1;

    ctx->rounds = nk + 6;
    int total = 4 * (ctx->rounds + 1);
    for (int i = 0; i < nk; i++)
        ctx->round_keys[i] = ((u32)key[i * 4] << 24) |
                             ((u32)key[i * 4 + 1] << 16) |
                             ((u32)key[i * 4 + 2] << 8) |
                             key[i * 4 + 3];
    for (int i = nk; i < total; i++) {
        u32 temp = ctx->round_keys[i - 1];
        if (i % nk == 0)
            temp = sub_word(rot_word(temp)) ^ g_rcon[i / nk];
        else if (nk > 6 && i % nk == 4)
            temp = sub_word(temp);
        ctx->round_keys[i] = ctx->round_keys[i - nk] ^ temp;
    }
    return 0;
}

static void add_round_key(u8 state[16], const u32 *words)
{
    for (int column = 0; column < 4; column++) {
        u32 word = words[column];
        state[column * 4] ^= (u8)(word >> 24);
        state[column * 4 + 1] ^= (u8)(word >> 16);
        state[column * 4 + 2] ^= (u8)(word >> 8);
        state[column * 4 + 3] ^= (u8)word;
    }
}

static void sub_bytes(u8 state[16])
{
    for (int i = 0; i < 16; i++)
        state[i] = g_sbox[state[i]];
}

static void inv_sub_bytes(u8 state[16])
{
    for (int i = 0; i < 16; i++)
        state[i] = g_inv_sbox[state[i]];
}

static void shift_rows(u8 state[16])
{
    u8 copy[16];
    memcpy(copy, state, 16);
    for (int row = 0; row < 4; row++)
        for (int column = 0; column < 4; column++)
            state[row + column * 4] =
                copy[row + ((column + row) % 4) * 4];
}

static void inv_shift_rows(u8 state[16])
{
    u8 copy[16];
    memcpy(copy, state, 16);
    for (int row = 0; row < 4; row++)
        for (int column = 0; column < 4; column++)
            state[row + column * 4] =
                copy[row + ((column - row + 4) % 4) * 4];
}

static void mix_columns(u8 state[16])
{
    for (int column = 0; column < 4; column++) {
        u8 *s = state + column * 4;
        u8 a0 = s[0], a1 = s[1], a2 = s[2], a3 = s[3];
        s[0] = (u8)(xtime(a0) ^ (xtime(a1) ^ a1) ^ a2 ^ a3);
        s[1] = (u8)(a0 ^ xtime(a1) ^ (xtime(a2) ^ a2) ^ a3);
        s[2] = (u8)(a0 ^ a1 ^ xtime(a2) ^ (xtime(a3) ^ a3));
        s[3] = (u8)((xtime(a0) ^ a0) ^ a1 ^ a2 ^ xtime(a3));
    }
}

static void inv_mix_columns(u8 state[16])
{
    for (int column = 0; column < 4; column++) {
        u8 *s = state + column * 4;
        u8 a0 = s[0], a1 = s[1], a2 = s[2], a3 = s[3];
        s[0] = gmul(a0, 14) ^ gmul(a1, 11) ^ gmul(a2, 13) ^
               gmul(a3, 9);
        s[1] = gmul(a0, 9) ^ gmul(a1, 14) ^ gmul(a2, 11) ^
               gmul(a3, 13);
        s[2] = gmul(a0, 13) ^ gmul(a1, 9) ^ gmul(a2, 14) ^
               gmul(a3, 11);
        s[3] = gmul(a0, 11) ^ gmul(a1, 13) ^ gmul(a2, 9) ^
               gmul(a3, 14);
    }
}

void aes_encrypt_block(const struct aes_ctx *ctx, const u8 in[16],
                       u8 out[16])
{
    u8 state[16];
    memcpy(state, in, 16);
    add_round_key(state, ctx->round_keys);
    for (int round = 1; round < ctx->rounds; round++) {
        sub_bytes(state);
        shift_rows(state);
        mix_columns(state);
        add_round_key(state, ctx->round_keys + round * 4);
    }
    sub_bytes(state);
    shift_rows(state);
    add_round_key(state, ctx->round_keys + ctx->rounds * 4);
    memcpy(out, state, 16);
}

void aes_decrypt_block(const struct aes_ctx *ctx, const u8 in[16],
                       u8 out[16])
{
    u8 state[16];
    memcpy(state, in, 16);
    add_round_key(state, ctx->round_keys + ctx->rounds * 4);
    for (int round = ctx->rounds - 1; round >= 1; round--) {
        inv_shift_rows(state);
        inv_sub_bytes(state);
        add_round_key(state, ctx->round_keys + round * 4);
        inv_mix_columns(state);
    }
    inv_shift_rows(state);
    inv_sub_bytes(state);
    add_round_key(state, ctx->round_keys);
    memcpy(out, state, 16);
}

int aes_cbc_encrypt(const struct aes_ctx *ctx, const u8 iv[16],
                    const u8 *plain, usize length, u8 *out, usize capacity)
{
    if (!ctx || !iv || !out)
        return -1;
    usize padding = 16 - (length % 16);
    usize total = length + padding;
    if (total > capacity)
        return -1;
    u8 block[16];
    u8 chain[16];
    memcpy(chain, iv, 16);
    for (usize offset = 0; offset < total; offset += 16) {
        for (usize i = 0; i < 16; i++) {
            usize position = offset + i;
            block[i] = position < length
                           ? plain[position]
                           : (u8)padding;
        }
        for (int i = 0; i < 16; i++)
            block[i] ^= chain[i];
        aes_encrypt_block(ctx, block, out + offset);
        memcpy(chain, out + offset, 16);
    }
    return (int)total;
}

int aes_cbc_decrypt(const struct aes_ctx *ctx, const u8 iv[16],
                    const u8 *cipher, usize length, u8 *out, usize capacity)
{
    if (!ctx || !iv || !cipher || !length || (length % 16))
        return -1;
    if (length > capacity)
        return -1;
    u8 chain[16];
    u8 block[16];
    memcpy(chain, iv, 16);
    for (usize offset = 0; offset < length; offset += 16) {
        memcpy(block, cipher + offset, 16);
        aes_decrypt_block(ctx, block, out + offset);
        for (int i = 0; i < 16; i++)
            out[offset + i] ^= chain[i];
        memcpy(chain, block, 16);
    }
    u8 padding = out[length - 1];
    if (!padding || padding > 16 || padding > length)
        return -1;
    for (usize i = 0; i < padding; i++)
        if (out[length - 1 - i] != padding)
            return -1;
    return (int)(length - padding);
}
