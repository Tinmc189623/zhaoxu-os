; ZhaoxuBootloader - legacy BIOS stage 1
;
; 512-byte boot sector used both as an MBR (installed disk) and as the
; El Torito no-emulation boot image (ISO).  On an installed disk it loads
; stage 2 with INT 13h CHS reads; the ISO image builder marks this sector
; with stage2_lba = 0xFFFF instead, because the firmware already loaded the
; whole boot image (stage 2 sits at image offset 1024 = 0x8000).  Only the
; first 446 bytes are copied into an installed MBR, so the partition table
; and 0x55AA stay untouched there.

org 0x7C00
use16

STAGE2_LOAD = 0x8000

include 'build/bios_stage1.inc'        ; STAGE2_SECTORS, generated by the Makefile

start:
        cli
        xor     ax, ax
        mov     ds, ax
        mov     es, ax
        mov     ss, ax
        mov     sp, 0x7C00
        sti
        cld
        mov     [boot_drive], dl

        call    serial_init
        mov     si, msg_banner
        call    print

        mov     ax, [stage2_lba]
        cmp     ax, 0xFFFF              ; no-emulation ISO: stage 2 is resident
        je      .enter

        mov     dl, [boot_drive]
        mov     ah, 0x08
        int     0x13
        jc      fail
        and     cl, 0x3F
        jz      fail
        movzx   ax, cl
        mov     [spt], ax
        inc     dh
        movzx   ax, dh
        mov     [heads], ax

        mov     ax, 0x0800              ; stage 2 loads at 0x8000
        mov     es, ax
        xor     bx, bx
        mov     ax, [stage2_lba]        ; patched by the installer (1 or 34)
        mov     cx, STAGE2_SECTORS
        call    read_chs
        jc      fail

.enter:
        mov     dl, [boot_drive]
        db      0EAh                    ; jmp far 0x0000:0x8000
        dw      STAGE2_LOAD
        dw      0

fail:
        mov     si, msg_fail
        call    print
.halt:
        hlt
        jmp     .halt

; ------------------------------------------------------------------ helpers
; ES:BX <- CX sectors starting at LBA AX.  CF set on error.
read_chs:
        pusha
        push    es
        mov     [io_lba], ax
        mov     [io_count], cx
        mov     [io_buf], bx
        mov     [io_seg], es

        mov     ax, [io_lba]
        xor     dx, dx
        div     word [spt]
        inc     dx
        mov     [io_sector], dx
        xor     dx, dx
        div     word [heads]
        mov     [io_cyl], ax
        mov     [io_head], dx
.loop:
        mov     ax, [io_count]
        test    ax, ax
        jz      .ok
        mov     di, [spt]
        sub     di, [io_sector]
        inc     di
        cmp     ax, di
        jbe     .chunk
        mov     ax, di
.chunk:
        mov     [io_chunk], ax
        mov     es, [io_seg]
        mov     bx, [io_buf]
        mov     dl, byte [boot_drive]
        mov     ch, byte [io_cyl]
        mov     cl, byte [io_sector]
        mov     dh, byte [io_head]
        mov     al, byte [io_chunk]
        mov     ah, 0x02
        int     0x13
        jc      .error
        mov     si, [io_chunk]
        mov     ax, si
        shl     ax, 5                   ; chunk * 512 bytes = chunk * 0x20 paragraphs
        add     [io_seg], ax
        mov     word [io_buf], 0
        sub     [io_count], si
        jz      .ok
        add     [io_sector], si
        mov     ax, [spt]
        inc     ax
        cmp     [io_sector], ax
        jb      .loop
        mov     word [io_sector], 1
        inc     word [io_head]
        mov     al, byte [heads]
        cmp     byte [io_head], al
        jb      .loop
        mov     word [io_head], 0
        inc     word [io_cyl]
        jmp     .loop
.ok:
        pop     es
        popa
        clc
        ret
.error:
        pop     es
        popa
        stc
        ret

serial_init:
        mov     dx, 0x3F9
        xor     al, al
        out     dx, al
        mov     dx, 0x3FB
        mov     al, 0x80
        out     dx, al
        mov     dx, 0x3F8
        mov     al, 1
        out     dx, al
        mov     dx, 0x3F9
        xor     al, al
        out     dx, al
        mov     dx, 0x3FB
        mov     al, 3
        out     dx, al
        mov     dx, 0x3FA
        mov     al, 0xC7
        out     dx, al
        mov     dx, 0x3FC
        mov     al, 3
        out     dx, al
        ret

; SI -> ASCIIZ, written to both the BIOS console and COM1.
print:
        push    ax
        push    bx
        push    si
        push    dx
.loop:
        lodsb
        test    al, al
        jz      .done
        push    si
        push    ax
        mov     ah, 0x0E
        mov     bx, 7
        int     0x10
        pop     ax
        pop     si
        mov     dx, 0x3F8
        out     dx, al
        jmp     .loop
.done:
        pop     dx
        pop     si
        pop     bx
        pop     ax
        ret

stage2_marker   db 'ZSLBA'
stage2_lba      dw 1                    ; 0xFFFF = stage 2 already in memory (ISO)
boot_drive      db 0
spt             dw 18
heads           dw 2
io_lba          dw 0
io_count        dw 0
io_buf          dw 0
io_seg          dw 0
io_sector       dw 0
io_cyl          dw 0
io_head         dw 0
io_chunk        dw 0
msg_banner      db 13,10,'ZhaoxuBootloader stage1',13,10,0
msg_fail        db 'stage1: disk read failed',13,10,0

assert ($ - $$) <= 446

        rb      510 - ($ - $$)
        dw      0AA55h
