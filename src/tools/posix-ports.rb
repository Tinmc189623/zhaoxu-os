#!/usr/bin/env ruby
# frozen_string_literal: true

# posix-ports.rb -- build ncurses and nano for x86_64-elf against newlib.
#
# The ZXE user ABI is PIC, so every library is built with -fPIC.  autoconf
# rejects the repository path (it contains spaces), so the trees live under
# $HOME.  Run tools/newlib.rb first.
#
#   ruby tools/newlib.rb
#   ruby tools/posix-ports.rb

require "etc"
require "fileutils"

HOME = Dir.home
NEWLIB = File.join(HOME, "newlib", "install", "x86_64-elf")
XCOUT = File.join(HOME, "newlib", "xbin")
SUPPORT = File.join(HOME, "zosgloss")
NCURSES_SRC = File.join(HOME, "ncurses-src")
NCURSES_BUILD = File.join(HOME, "ncurses-build")
NANO_SRC = File.join(HOME, "nano-src")
NANO_BUILD = File.join(HOME, "nano-build")
FASTINC = File.join(HOME, "fastinc")
REPO = File.expand_path("..", __dir__)
WRAPPER = File.join(XCOUT, "x86_64-elf-gcc")

ENV["PATH"] = "/usr/local/bin:/usr/bin:/bin:#{XCOUT}"

def run(command, chdir: HOME, env: {})
  puts "+ #{command.join(' ')}"
  ok = system(env, *command, chdir: chdir)
  raise "command failed: #{command.join(' ')}" unless ok
end

def write_wrapper
  FileUtils.mkdir_p(XCOUT)
  File.write(WRAPPER, <<~RB)
    #!/usr/bin/env ruby
    # Generated by tools/posix-ports.rb: x86_64-elf clang wrapper.
    exec "clang",
         "--target=x86_64-unknown-elf", "-fPIC", "-ffreestanding",
         "-fno-builtin", "-fno-stack-protector",
         "-fno-asynchronous-unwind-tables", "-mno-red-zone",
         "-nostdinc", "-isystem", "/usr/lib/llvm-21/lib/clang/21/include",
         "-isystem", "#{REPO}/user/lib/posix/include",
         "-isystem", "#{NEWLIB}/include",
         "-L#{NEWLIB}/lib",
         "-Wl,-e,main", "-nostartfiles", *ARGV,
         "-Wl,--start-group", "#{SUPPORT}/libgloss.a",
         "-lc", "-lm", "-Wl,--end-group"
  RB
  File.chmod(0o755, WRAPPER)
end

def build_support
  FileUtils.mkdir_p(SUPPORT)
  %w[libgloss glob].each do |name|
    run([WRAPPER, "-c", "#{REPO}/user/lib/posix/#{name}.c",
         "-o", "#{SUPPORT}/#{name}.o"])
  end
  run(%w[llvm-ar-21 rcs] + [File.join(SUPPORT, "libgloss.a")] +
      %w[libgloss.o glob.o].map { |o| File.join(SUPPORT, o) })
end

def fetch(url, target)
  return if File.file?(target)
  run(["wget", "-q", "--timeout=180", "-O", target, url])
end

def build_ncurses
  FileUtils.mkdir_p(NCURSES_SRC)
  fetch("https://ftp.gnu.org/gnu/ncurses/ncurses-6.5.tar.gz",
        File.join(NCURSES_SRC, "ncurses.tar.gz"))
  unless File.file?(File.join(NCURSES_SRC, "configure"))
    run(["tar", "-xf", File.join(NCURSES_SRC, "ncurses.tar.gz"), "-C",
         NCURSES_SRC, "--strip-components=1"])
  end
  FileUtils.rm_rf(NCURSES_BUILD)
  FileUtils.mkdir_p(NCURSES_BUILD)
  run([File.join(NCURSES_SRC, "configure"),
       "--host=x86_64-elf", "--build=x86_64-pc-linux-gnu",
       "--prefix=#{HOME}/ncurses-install", "--without-shared",
       "--without-debug", "--without-ada", "--without-manpages",
       "--without-progs", "--without-tests", "--disable-widec",
       "--with-termlib"], chdir: NCURSES_BUILD,
      env: { "CC_FOR_BUILD" => "gcc" })
  config = File.join(NCURSES_BUILD, "include", "ncurses_cfg.h")
  text = File.read(config).lines.reject do |line|
    line =~ /\A#define (const|inline|intptr_t long|ssize_t int|pid_t int)\n?\z/
  end.join
  File.write(config, text)
  run(["make", "-j#{Etc.nprocessors}", "ARFLAGS=rv"], chdir: NCURSES_BUILD)
end

def build_nano
  FileUtils.mkdir_p(NANO_SRC)
  fetch("https://ftp.gnu.org/gnu/nano/nano-8.4.tar.xz",
        File.join(NANO_SRC, "nano.tar.xz"))
  unless File.file?(File.join(NANO_SRC, "configure"))
    run(["tar", "-xf", File.join(NANO_SRC, "nano.tar.xz"), "-C", NANO_SRC,
         "--strip-components=1"])
  end
  FileUtils.mkdir_p(FASTINC)
  File.write(File.join(FASTINC, "signal.h"), <<~H)
    #ifndef ZOS_FAST_SIGNAL
    #define ZOS_FAST_SIGNAL
    #include "#{NEWLIB}/include/signal.h"
    #ifndef SA_RESETHAND
    #define SA_RESETHAND 0x80000000
    #endif
    #ifndef SA_NODEFER
    #define SA_NODEFER 0x40000000
    #endif
    #endif
  H
  cache = File.join(HOME, "nano.cache")
  File.write(cache, <<~C)
    gl_cv_func_strcasecmp_works=yes
    ac_cv_header_dirent_h=yes
    ac_cv_func_opendir=yes
    ac_cv_func_readdir=yes
    ac_cv_func_closedir=yes
    ac_cv_func_fdopendir=no
    ac_cv_header_glob_h=yes
    ac_cv_func_glob=yes
    ac_cv_func_globfree=yes
    ac_cv_func_fnmatch=yes
    ac_cv_func_getprogname=yes
    ac_cv_func_sigaction=yes
    ac_cv_func_sigprocmask=yes
    ac_cv_func_sigemptyset=yes
    ac_cv_func_sigfillset=yes
    ac_cv_func_sigaddset=yes
    ac_cv_func_sigdelset=yes
    ac_cv_func_sigismember=yes
  C
  FileUtils.rm_rf(NANO_BUILD)
  FileUtils.mkdir_p(NANO_BUILD)
  run([File.join(NANO_SRC, "configure"),
       "--host=x86_64-elf", "--build=x86_64-pc-linux-gnu",
       "--prefix=#{HOME}/nano-install", "--cache-file=#{cache}",
       "--disable-nls", "--disable-utf8", "--disable-browser",
       "--disable-speller", "--disable-extra"], chdir: NANO_BUILD,
      env: { "CC" => "#{WRAPPER} -I#{FASTINC}", "CC_FOR_BUILD" => "gcc",
             "CPPFLAGS" => "-DOK_TO_USE_1S_CLOCK -I#{HOME}/ncurses-build/include",
             "LDFLAGS" => "-L#{HOME}/ncurses-build/lib",
             "LIBS" => "-lncurses -ltinfo" })
  run(["make", "-j#{Etc.nprocessors}"], chdir: NANO_BUILD)
  puts "nano: #{File.join(NANO_BUILD, 'src', 'nano')}"
end

raise "newlib is missing; run ruby tools/newlib.rb" unless File.file?(File.join(NEWLIB, "lib", "libc.a"))

if ARGV.include?("--wrapper-only")
  write_wrapper
  exit 0
end

write_wrapper
build_support
build_ncurses
build_nano
