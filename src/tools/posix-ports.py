#!/usr/bin/env python3
"""Build ncurses and nano for x86_64-elf against newlib.

The ZXE user ABI is PIC, so every library is built with -fPIC.  autoconf
rejects the repository path (it contains spaces), so the trees live under
$HOME.  Run tools/newlib.py first.

    python3 tools/newlib.py
    python3 tools/posix-ports.py
"""

import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

HOME = Path.home()
NEWLIB = HOME / "newlib" / "install" / "x86_64-elf"
XCOUT = HOME / "newlib" / "xbin"
SUPPORT = HOME / "zosgloss"
NCURSES_SRC = HOME / "ncurses-src"
NCURSES_BUILD = HOME / "ncurses-build"
NANO_SRC = HOME / "nano-src"
NANO_BUILD = HOME / "nano-build"
FASTINC = HOME / "fastinc"
REPO = Path(__file__).resolve().parent.parent
WRAPPER = XCOUT / "x86_64-elf-gcc"

os.environ["PATH"] = f"/usr/local/bin:/usr/bin:/bin:{XCOUT}"


def run(command: list[str], chdir: Path = HOME,
        env: dict[str, str] | None = None) -> None:
    """Echo and execute one step, aborting on failure."""
    print("+ " + " ".join(str(part) for part in command))
    merged = dict(os.environ)
    if env:
        merged.update(env)
    if subprocess.run([str(part) for part in command], cwd=str(chdir), env=merged,
                      check=False).returncode != 0:
        raise SystemExit("command failed: " + " ".join(str(part) for part in command))


def write_wrapper() -> None:
    """Write the x86_64-elf clang wrapper used by ncurses and nano."""
    XCOUT.mkdir(parents=True, exist_ok=True)
    body = f"""#!/bin/sh
# Generated by tools/posix-ports.py: x86_64-elf clang wrapper.
exec clang --target=x86_64-unknown-elf -fPIC -ffreestanding -fno-builtin \\
  -fno-stack-protector -fno-asynchronous-unwind-tables -mno-red-zone \\
  -nostdinc -isystem /usr/lib/llvm-21/lib/clang/21/include \\
  -isystem {REPO}/user/lib/posix/include \\
  -isystem {NEWLIB}/include \\
  -L{NEWLIB}/lib \\
  -Wl,-e,main -nostartfiles "$@" \\
  -Wl,--start-group {SUPPORT}/libgloss.a -lc -lm -Wl,--end-group
"""
    WRAPPER.write_text(body, encoding="utf-8")
    WRAPPER.chmod(0o755)


def build_support() -> None:
    """Compile the POSIX glue into libgloss.a."""
    SUPPORT.mkdir(parents=True, exist_ok=True)
    names = ["libgloss", "posix_termios", "posix_signal", "posix_account",
             "posix_path", "posix_dirent", "posix_rlimit", "posix_time"]
    objects = []
    for name in names:
        obj = SUPPORT / f"{name}.o"
        run([str(WRAPPER), "-c", str(REPO / "user" / "lib" / "posix" / f"{name}.c"),
             "-o", str(obj)])
        objects.append(str(obj))
    run(["llvm-ar-21", "rcs", str(SUPPORT / "libgloss.a"), *objects])


def fetch(url: str, target: Path) -> None:
    """Download a tarball once."""
    if target.is_file():
        return
    run(["wget", "-q", "--timeout=180", "-O", str(target), url])


def build_ncurses() -> None:
    """Configure and build ncurses 6.5 for the target."""
    NCURSES_SRC.mkdir(parents=True, exist_ok=True)
    fetch("https://ftp.gnu.org/gnu/ncurses/ncurses-6.5.tar.gz",
          NCURSES_SRC / "ncurses.tar.gz")
    if not (NCURSES_SRC / "configure").is_file():
        run(["tar", "-xf", str(NCURSES_SRC / "ncurses.tar.gz"),
             "-C", str(NCURSES_SRC), "--strip-components=1"])

    shutil.rmtree(NCURSES_BUILD, ignore_errors=True)
    NCURSES_BUILD.mkdir(parents=True, exist_ok=True)
    run([str(NCURSES_SRC / "configure"),
         "--host=x86_64-elf", "--build=x86_64-pc-linux-gnu",
         f"--prefix={HOME}/ncurses-install", "--without-shared",
         "--without-debug", "--without-ada", "--without-manpages",
         "--without-progs", "--without-tests", "--disable-widec",
         "--with-termlib"], chdir=NCURSES_BUILD, env={"CC_FOR_BUILD": "gcc"})

    config = NCURSES_BUILD / "include" / "ncurses_cfg.h"
    pattern = re.compile(r"^#define (const|inline|intptr_t long|ssize_t int|pid_t int)$")
    lines = [line for line in config.read_text(encoding="utf-8").splitlines()
             if not pattern.match(line)]
    config.write_text("\n".join(lines) + "\n", encoding="utf-8")

    run(["make", f"-j{os.cpu_count() or 4}", "ARFLAGS=rv"], chdir=NCURSES_BUILD)


def build_nano() -> None:
    """Configure and build nano 8.4 against ncurses."""
    NANO_SRC.mkdir(parents=True, exist_ok=True)
    fetch("https://ftp.gnu.org/gnu/nano/nano-8.4.tar.xz", NANO_SRC / "nano.tar.xz")
    if not (NANO_SRC / "configure").is_file():
        run(["tar", "-xf", str(NANO_SRC / "nano.tar.xz"), "-C", str(NANO_SRC),
             "--strip-components=1"])

    FASTINC.mkdir(parents=True, exist_ok=True)
    (FASTINC / "signal.h").write_text(
        "#ifndef ZOS_FAST_SIGNAL\n"
        "#define ZOS_FAST_SIGNAL\n"
        f'#include "{NEWLIB}/include/signal.h"\n'
        "#ifndef SA_RESETHAND\n#define SA_RESETHAND 0x80000000\n#endif\n"
        "#ifndef SA_NODEFER\n#define SA_NODEFER 0x40000000\n#endif\n"
        "#endif\n",
        encoding="utf-8",
    )

    cache = HOME / "nano.cache"
    cache.write_text(
        "gl_cv_func_strcasecmp_works=yes\n"
        "ac_cv_header_dirent_h=yes\n"
        "ac_cv_func_opendir=yes\n"
        "ac_cv_func_readdir=yes\n"
        "ac_cv_func_closedir=yes\n"
        "ac_cv_func_fdopendir=no\n"
        "ac_cv_header_glob_h=no\n"
        "ac_cv_func_glob=no\n"
        "ac_cv_func_globfree=no\n"
        "ac_cv_func_fnmatch=no\n"
        "ac_cv_func_getprogname=yes\n"
        "ac_cv_func_sigaction=yes\n"
        "ac_cv_func_sigprocmask=yes\n"
        "ac_cv_func_sigemptyset=yes\n"
        "ac_cv_func_sigfillset=yes\n"
        "ac_cv_func_sigaddset=yes\n"
        "ac_cv_func_sigdelset=yes\n"
        "ac_cv_func_sigismember=yes\n",
        encoding="utf-8",
    )

    shutil.rmtree(NANO_BUILD, ignore_errors=True)
    NANO_BUILD.mkdir(parents=True, exist_ok=True)
    run([str(NANO_SRC / "configure"),
         "--host=x86_64-elf", "--build=x86_64-pc-linux-gnu",
         f"--prefix={HOME}/nano-install", f"--cache-file={cache}",
         "--disable-nls", "--disable-utf8", "--disable-browser",
         "--disable-speller", "--disable-extra"],
        chdir=NANO_BUILD,
        env={
            "CC": f"{WRAPPER} -I{FASTINC}",
            "CC_FOR_BUILD": "gcc",
            "CPPFLAGS": f"-D_GNU_SOURCE -DFNM_EXTMATCH=32 -DOK_TO_USE_1S_CLOCK "
                        f"-I{HOME}/ncurses-build/include",
            "LDFLAGS": f"-L{HOME}/ncurses-build/lib",
            "LIBS": "-lncurses -ltinfo",
        })
    run(["make", f"-j{os.cpu_count() or 4}"], chdir=NANO_BUILD)
    print(f"nano: {NANO_BUILD / 'src' / 'nano'}")


def main(argv: list[str]) -> int:
    if not (NEWLIB / "lib" / "libc.a").is_file():
        raise SystemExit("newlib is missing; run python3 tools/newlib.py")

    write_wrapper()
    if "--wrapper-only" in argv:
        return 0

    build_support()
    build_ncurses()
    build_nano()
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
